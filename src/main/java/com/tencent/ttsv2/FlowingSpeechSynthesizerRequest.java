package com.tencent.ttsv2;

import com.google.gson.annotations.SerializedName;
import com.tencent.core.ws.CommonRequest;

import java.util.Map;

/**
 * TextToStreamAudioWSV2 request parameters.
 */
public class FlowingSpeechSynthesizerRequest extends CommonRequest {
    /**
     * API action name. The value is: TextToStreamAudioWSV2.
     */
    @SerializedName("Action")
    private String action;

    /**
     * Account AppId. Please make sure the data type of this field is int.
     */
    @SerializedName("AppId")
    private Integer appId;

    /**
     * SecretId of the Tencent Cloud registered account, which can be obtained from the API key management page.
     */
    @SerializedName("SecretId")
    private String secretid;

    /**
     * The current UNIX timestamp, which records the time the API request is initiated. If it differs too much from the current time, a signature-expired error will occur. Simply use the system timestamp of the current request.
     */
    @SerializedName("Timestamp")
    protected Long timestamp;

    /**
     * The signature validity period, a value conforming to the UNIX Epoch timestamp specification, in seconds. Expired must be greater than Timestamp, and (Expired - Timestamp) must be less than 90 days.
     */
    @SerializedName("Expired")
    protected Long expired;


    /**
     * Required.
     * The globally unique identifier for the speech synthesis session. Each WebSocket connection corresponds to one such identifier. It is generated by the user (UUID is recommended) and can be up to 128 characters long.
     */
    @SerializedName("SessionId")
    private String sessionId;


    /**
     * Optional.
     * Int: see the VoiceType parameter in the Speech Synthesis API documentation for details.
     */
    @SerializedName("VoiceType")
    private Integer voiceType;

    /**
     * Volume level, range [-10, 10], corresponding to different volume levels.
     * Default is 0, representing normal volume. A larger value means higher volume.
     */
    @SerializedName("Volume")
    private Float volume;


    /**
     * Speech rate, range [-2, 6], corresponding to different rates:
     * -2: 0.6x
     * -1: 0.8x
     * 0: 1.0x (default)
     * 1: 1.2x
     * 2: 1.5x
     * 6: 2.5x
     * If a finer speech rate is required, two decimal digits are supported, e.g. 0.5 / 1.25 / 2.81, etc.
     * For the conversion between parameter value and actual speech rate, refer to the code example.
     */
    @SerializedName("Speed")
    private Float speed;
    /**
     * Audio sample rate:
     * 24000: 24k (supported by some voice types; see the voice list)
     * 16000: 16k (default)
     * 8000: 8k
     */
    @SerializedName("SampleRate")
    private Integer sampleRate;


    /**
     * Returned audio format:
     * pcm: returns binary pcm audio (default).
     * mp3: returns binary mp3 audio.
     */
    @SerializedName("Codec")
    private String codec;

    /**
     * Whether to enable timestamps. Default is false.
     */
    @SerializedName("EnableSubtitle")
    private Boolean enableSubtitle;

    /**
     * Controls the emotion of the synthesized audio. Only supported by multi-emotion voice types. Values: neutral (neutral), sad (sad), happy (happy), angry (angry), fear (fear), news (news), story (story), radio (radio), poetry (poetry), call (customer service), sajiao (coquettish), disgusted (disgusted), amaze (amazed), peaceful (peaceful), exciting (exciting), aojiao (tsundere), jieshuo (narration).
     * Example value: neutral.
     */
    @SerializedName("EmotionCategory")
    private String emotionCategory;
    /**
     * Controls the emotion intensity of the synthesized audio. Range: [50, 200], default 100. Only takes effect when EmotionCategory is not empty.
     */
    @SerializedName("EmotionIntensity")
    private Integer emotionIntensity;

    /**
     * Sentence-break sensitivity threshold. Range: [0, 1, 2]. Default: 0.
     * The larger this value, the less likely the text will be broken; the model will lean more towards breaking only on punctuation. Do not adjust this parameter arbitrarily, as it may affect the synthesis effect.
     */
    @SerializedName("SegmentRate")
    private Integer segmentRate;

    /**
     * Account area.
     * 0: China account (default)
     * 1: International account
     */
    @SerializedName("AccountArea")
    private String accountArea;

    public Integer getSegmentRate() {
        return segmentRate;
    }

    public void setSegmentRate(Integer segmentRate) {
        this.segmentRate = segmentRate;
    }

    public String getSecretid() {
        return secretid;
    }

    public void setSecretid(String secretid) {
        this.secretid = secretid;
    }

    public Long getTimestamp() {
        return timestamp;
    }

    public void setTimestamp(Long timestamp) {
        this.timestamp = timestamp;
    }

    public Long getExpired() {
        return expired;
    }

    public void setExpired(Long expired) {
        this.expired = expired;
    }

    public String getSessionId() {
        return sessionId;
    }

    public void setSessionId(String sessionId) {
        this.sessionId = sessionId;
    }

    public Integer getVoiceType() {
        return voiceType;
    }

    public void setVoiceType(Integer voiceType) {
        this.voiceType = voiceType;
    }

    public Float getVolume() {
        return volume;
    }

    public void setVolume(Float volume) {
        this.volume = volume;
    }

    public Float getSpeed() {
        return speed;
    }

    public void setSpeed(Float speed) {
        this.speed = speed;
    }

    public Integer getSampleRate() {
        return sampleRate;
    }

    public void setSampleRate(Integer sampleRate) {
        this.sampleRate = sampleRate;
    }

    public String getCodec() {
        return codec;
    }

    public void setCodec(String codec) {
        this.codec = codec;
    }

    public Boolean getEnableSubtitle() {
        return enableSubtitle;
    }

    public void setEnableSubtitle(Boolean enableSubtitle) {
        this.enableSubtitle = enableSubtitle;
    }

    public String getEmotionCategory() {
        return emotionCategory;
    }

    public void setEmotionCategory(String emotionCategory) {
        this.emotionCategory = emotionCategory;
    }

    public Integer getEmotionIntensity() {
        return emotionIntensity;
    }

    public void setEmotionIntensity(Integer emotionIntensity) {
        this.emotionIntensity = emotionIntensity;
    }

    public String getAction() {
        return action;
    }

    public void setAction(String action) {
        this.action = action;
    }

    public Integer getAppId() {
        return appId;
    }

    public void setAppId(Integer appId) {
        this.appId = appId;
    }

    public String getAccountArea() {
        return accountArea;
    }

    public void setAccountArea(String accountArea) {
        this.accountArea = accountArea;
    }

    public Map<String, Object> toTreeMap() {
        Map<String, Object> src = super.toTreeMap();
        if (src != null) {
            for (String key : src.keySet()) {
                if (src.get(key) instanceof Float) {
                    Float value = Float.parseFloat(src.get(key).toString());
                    if (value != null && value.intValue() == value) {
                        src.put(key, value.intValue());
                    } else {
                        src.put(key, value);
                    }
                }
            }
        }
        return src;
    }
}
